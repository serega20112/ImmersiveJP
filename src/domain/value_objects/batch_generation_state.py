from enum import StrEnum


class BatchGenerationState(StrEnum):
    """Состояние генерации партии карточек.

    Состояние живёт в базе, а не в памяти процесса: генерация идёт фоном, а
    страницу могут перезагрузить или сервис могут перезапустить посреди неё.
    Хранение статуса в памяти оставило бы пользователя с вечным «готовим».

    Значения:
        READY: партии нет или она сгенерирована целиком — можно работать дальше.
        GENERATING: партия забронирована и дописывается карточка за карточкой.
        FAILED: генерация оборвалась, партия неполная и ждёт повторного запуска.
    """

    READY = "ready"
    GENERATING = "generating"
    FAILED = "failed"

    @property
    def is_terminal(self) -> bool:
        """Находится ли состояние в конечном, не требующим опроса."""
        return self is not BatchGenerationState.GENERATING
